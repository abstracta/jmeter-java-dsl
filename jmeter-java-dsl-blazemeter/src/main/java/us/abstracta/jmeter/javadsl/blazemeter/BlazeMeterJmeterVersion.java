package us.abstracta.jmeter.javadsl.blazemeter;

/**
 * Specifies the JMeter version BlazeMeter engines use to run a test plan.
 * <p>
 * BlazeMeter does not allow specifying an arbitrary JMeter version, only these aliases.
 *
 * @see BlazeMeterEngine#jmeterVersion(BlazeMeterJmeterVersion)
 * @since 2.4
 */
public enum BlazeMeterJmeterVersion {
  /**
   * The JMeter version BlazeMeter considers stable (e.g. 5.5).
   */
  STABLE("stable"),
  /**
   * The latest JMeter version supported by BlazeMeter (e.g. 5.6.3).
   */
  LATEST("latest"),
  /**
   * Makes BlazeMeter use the JMeter version declared in the test plan, which for test plans
   * generated by JMeter DSL is the JMeter version JMeter DSL depends on.
   * <p>
   * This option requires enabling JMeter version auto-detect in BlazeMeter account settings, which
   * is only available for accounts with private locations.
   */
  AUTO("auto");

  private final String name;

  BlazeMeterJmeterVersion(String name) {
    this.name = name;
  }

  public String getName() {
    return name;
  }

}
